// Opening lines for the people in generated cases. Large pools, handed out
// by rotation so neighbouring cases never open the same way.
// {m|f} follows the speaker unless noted; {name} is a suspect's name.

/** The k-th line for case n: consecutive cases always land on different lines. */
export function rot<T>(list: readonly T[], n: number, k = 0): T {
  return list[(n * 5 + k * 7) % list.length];
}

