/** The partner's lines for a map, shuffled so each patrol sounds different. */
export function partnerQuips(mapId: string): string[] {
  const list = [...(BY_MAP[mapId] ?? []), ...GENERAL];
  for (let i = list.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [list[i], list[j]] = [list[j], list[i]];
  }
  return list;
}
