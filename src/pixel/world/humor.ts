/** Picks the masculine or feminine form for the detective. */
export type G = (male: string, female: string) => string;

/** Resolves {masculine|feminine} markers in a line addressed to the detective. */
export function genderize(text: string, form: 'male' | 'female'): string {
  return text.replace(/\{([^|{}]*)\|([^|{}]*)\}/g, (_, m: string, f: string) => (form === 'female' ? f : m));
}

